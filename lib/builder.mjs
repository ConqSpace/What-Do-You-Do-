export function builderInfo(rules) {
  if (rules === 'dw') {
    return {
      stats: dw.STATS.map((s) => ({ name: s, help: DW_STATS[s] })),
      scores: dw.meta().scores,
      basicMoves: Object.keys(dw.MOVES).filter((n) => n !== '마지막 숨'),
      classes: Object.entries(dw.CLASSES).map(([name, c]) => ({
        name, hp: c.hp, damage: c.damage, armor: c.armor, passives: c.passives,
        moves: Object.entries(c.moves || {}).map(([n, m]) => ({ name: n, stat: m.stat, when: m.when, strong: m.strong, weak: m.weak })),
        ...DW_CLASSES[name],
        scores: Object.fromEntries(dw.STATS.map((s, i) => [s, DW_CLASSES[name].scores[i]])),
        alignments: Object.entries(DW_CLASSES[name].alignments).map(([a, motive]) => ({ name: a, motive })),
      })),
      bonds: DW_BONDS, motives: MOTIVES, personality: PERSONALITY,
    };
  }
  if (rules === 'coc7') {
    return {
      chars: coc7.STATS.map((k) => ({ name: k, ...COC_CHARS[k] })),
      luck: { help: '운. 운에 맡기는 판정과, 실패한 판정을 메우는 데 쓴다', dice: '3d6×5' },
      quick: QUICK_FIRE, pointBuy: POINT_BUY,
      skills: coc7.SKILLS,
      occupations: Object.entries(COC_OCCUPATIONS).map(([name, o]) => ({ name, ...o })),
      personal: COC_PERSONAL, backstory: COC_BACKSTORY, gear: COC_GEAR, personality: PERSONALITY,
    };
  }
  const m = d20.meta();
  return {
    stats: m.stats.map((s) => ({ name: s, help: D20_STATS[s] })),
    min: m.statMin, max: m.statMax, budget: m.budget,
    looks: LOOKS, personality: PERSONALITY, backstory: D20_BACKSTORY,
  };
}
